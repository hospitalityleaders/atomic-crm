CREATE TABLE contact_notes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id UUID NOT NULL REFERENCES crm_workspaces(id) ON DELETE CASCADE,
  contact_id BIGINT NOT NULL,
  text TEXT,
  date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  sales_id BIGINT REFERENCES sales(id),
  status TEXT,
  attachments JSONB NOT NULL DEFAULT '[]'::JSONB,
  FOREIGN KEY (workspace_id, contact_id)
    REFERENCES contacts(workspace_id, id) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE deals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id UUID NOT NULL REFERENCES crm_workspaces(id) ON DELETE CASCADE,
  pipeline_id UUID NOT NULL,
  name TEXT NOT NULL,
  company_id BIGINT,
  contact_ids BIGINT[] NOT NULL DEFAULT '{}',
  category TEXT,
  stage UUID NOT NULL,
  description TEXT,
  amount BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  archived_at TIMESTAMPTZ,
  archived_by_user_id UUID REFERENCES crm_users(id) ON DELETE SET NULL,
  archived_stage_id UUID,
  archived_position NUMERIC(20, 8),
  expected_closing_date DATE,
  sales_id BIGINT REFERENCES sales(id),
  index NUMERIC(20, 8) NOT NULL DEFAULT 0,
  UNIQUE (workspace_id, id),
  FOREIGN KEY (workspace_id, pipeline_id)
    REFERENCES crm_pipelines(workspace_id, id) ON DELETE RESTRICT,
  FOREIGN KEY (workspace_id, stage)
    REFERENCES crm_pipeline_stages(workspace_id, id) ON DELETE RESTRICT,
  FOREIGN KEY (workspace_id, archived_stage_id)
    REFERENCES crm_pipeline_stages(workspace_id, id) ON DELETE RESTRICT,
  FOREIGN KEY (workspace_id, company_id)
    REFERENCES companies(workspace_id, id) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE deal_notes (
