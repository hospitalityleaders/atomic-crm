  email_jsonb JSONB NOT NULL DEFAULT '[]'::JSONB,
  phone_jsonb JSONB NOT NULL DEFAULT '[]'::JSONB,
  UNIQUE (workspace_id, id),
  FOREIGN KEY (workspace_id, company_id)
