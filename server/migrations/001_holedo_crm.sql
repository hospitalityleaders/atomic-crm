CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE crm_users (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  keycloak_subject TEXT NOT NULL UNIQUE,
  email TEXT NOT NULL DEFAULT '',
  display_name TEXT NOT NULL,
  first_name TEXT NOT NULL DEFAULT '',
  last_name TEXT NOT NULL DEFAULT '',
  platform_admin BOOLEAN NOT NULL DEFAULT FALSE,
  last_login_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE crm_workspaces (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  workspace_type TEXT NOT NULL CHECK (workspace_type IN ('personal', 'company')),
  name TEXT NOT NULL,
  owner_user_id UUID NOT NULL REFERENCES crm_users(id) ON DELETE RESTRICT,
  subscription_state TEXT NOT NULL DEFAULT 'active'
    CHECK (subscription_state IN ('active', 'grace', 'suspended', 'cancelled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (id, workspace_type)
);

CREATE UNIQUE INDEX crm_one_personal_workspace_per_owner
  ON crm_workspaces (owner_user_id) WHERE workspace_type = 'personal';

CREATE TABLE crm_workspace_members (
  workspace_id UUID NOT NULL,
  workspace_type TEXT NOT NULL CHECK (workspace_type IN ('personal', 'company')),
  user_id UUID NOT NULL REFERENCES crm_users(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('owner', 'administrator', 'editor', 'viewer')),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (workspace_id, user_id),
  FOREIGN KEY (workspace_id, workspace_type)
    REFERENCES crm_workspaces(id, workspace_type) ON DELETE CASCADE
);

CREATE UNIQUE INDEX crm_one_company_membership_per_user
  ON crm_workspace_members (user_id)
  WHERE workspace_type = 'company' AND status IN ('active', 'suspended');

CREATE INDEX crm_workspace_members_user_idx
  ON crm_workspace_members (user_id, status);

CREATE TABLE crm_workspace_invitations (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  workspace_id UUID NOT NULL REFERENCES crm_workspaces(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('administrator', 'editor', 'viewer')),
  token_hash TEXT UNIQUE,
  invited_by_user_id UUID NOT NULL REFERENCES crm_users(id) ON DELETE RESTRICT,
  expires_at TIMESTAMPTZ NOT NULL,
  accepted_at TIMESTAMPTZ,
  revoked_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX crm_open_invitation_per_company_email
  ON crm_workspace_invitations (workspace_id, lower(email))
  WHERE accepted_at IS NULL AND revoked_at IS NULL;

CREATE TABLE crm_oidc_flows (
  token_hash TEXT PRIMARY KEY,
  state TEXT NOT NULL,
  nonce TEXT NOT NULL,
  code_verifier TEXT NOT NULL,
  return_to TEXT NOT NULL DEFAULT '/',
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX crm_oidc_flows_expiry_idx ON crm_oidc_flows (expires_at);

CREATE TABLE crm_sessions (
  token_hash TEXT PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES crm_users(id) ON DELETE CASCADE,
  active_workspace_id UUID NOT NULL REFERENCES crm_workspaces(id) ON DELETE CASCADE,
  keycloak_session_id TEXT,
  refresh_token_encrypted TEXT,
  id_token_encrypted TEXT,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX crm_sessions_user_idx ON crm_sessions (user_id);
CREATE INDEX crm_sessions_keycloak_session_idx ON crm_sessions (keycloak_session_id);
CREATE INDEX crm_sessions_expiry_idx ON crm_sessions (expires_at);

CREATE TABLE sales (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id UUID NOT NULL REFERENCES crm_workspaces(id) ON DELETE CASCADE,
  crm_user_id UUID REFERENCES crm_users(id) ON DELETE SET NULL,
  first_name TEXT NOT NULL DEFAULT 'Pending',
  last_name TEXT NOT NULL DEFAULT 'Pending',
  email TEXT NOT NULL,
  administrator BOOLEAN NOT NULL DEFAULT FALSE,
  avatar JSONB,
  disabled BOOLEAN NOT NULL DEFAULT FALSE,
  secondary_emails JSONB NOT NULL DEFAULT '[]'::JSONB,
  UNIQUE (workspace_id, crm_user_id)
);

CREATE TABLE crm_pipelines (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  workspace_id UUID NOT NULL REFERENCES crm_workspaces(id) ON DELETE CASCADE,
  name TEXT NOT NULL DEFAULT 'Sales pipeline',
  is_primary BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (workspace_id, id)
);

CREATE UNIQUE INDEX crm_one_primary_pipeline_per_workspace
  ON crm_pipelines (workspace_id) WHERE is_primary;

CREATE TABLE crm_pipeline_stages (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  workspace_id UUID NOT NULL REFERENCES crm_workspaces(id) ON DELETE CASCADE,
  pipeline_id UUID NOT NULL,
  name TEXT NOT NULL,
  stage_kind TEXT NOT NULL DEFAULT 'open' CHECK (stage_kind IN ('open', 'won', 'lost')),
  position NUMERIC(20, 8) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (workspace_id, id),
  FOREIGN KEY (workspace_id, pipeline_id)
    REFERENCES crm_pipelines(workspace_id, id) ON DELETE CASCADE
);

CREATE TABLE companies (
