CREATE TABLE contacts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id UUID NOT NULL REFERENCES crm_workspaces(id) ON DELETE CASCADE,
  first_name TEXT,
  last_name TEXT,
  gender TEXT,
  title TEXT,
  background TEXT,
  avatar JSONB,
  first_seen TIMESTAMPTZ,
  last_seen TIMESTAMPTZ,
  has_newsletter BOOLEAN NOT NULL DEFAULT FALSE,
  status TEXT,
  tags BIGINT[] NOT NULL DEFAULT '{}',
  company_id BIGINT,
  sales_id BIGINT REFERENCES sales(id),
