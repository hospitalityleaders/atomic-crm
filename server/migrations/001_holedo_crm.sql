CREATE OR REPLACE VIEW companies_summary WITH (security_invoker = on) AS
SELECT c.*, count(DISTINCT d.id) AS nb_deals, count(DISTINCT co.id) AS nb_contacts
FROM companies c
LEFT JOIN deals d ON d.workspace_id = c.workspace_id AND d.company_id = c.id
LEFT JOIN contacts co ON co.workspace_id = c.workspace_id AND co.company_id = c.id
GROUP BY c.id;

CREATE OR REPLACE VIEW contacts_summary WITH (security_invoker = on) AS
SELECT co.*,
  jsonb_path_query_array(co.email_jsonb, '$[*]."email"')::TEXT AS email_fts,
  jsonb_path_query_array(co.phone_jsonb, '$[*]."number"')::TEXT AS phone_fts,
  c.name AS company_name,
  count(DISTINCT t.id) FILTER (WHERE t.done_date IS NULL) AS nb_tasks
FROM contacts co
LEFT JOIN tasks t ON t.workspace_id = co.workspace_id AND t.contact_id = co.id
LEFT JOIN companies c ON c.workspace_id = co.workspace_id AND c.id = co.company_id
GROUP BY co.id, c.name;

CREATE OR REPLACE VIEW activity_log WITH (security_invoker = on) AS
SELECT ('company.' || c.id || '.created') AS id, c.workspace_id,
  'company.created' AS type, c.created_at AS date, c.id AS company_id, c.sales_id,
  to_json(c.*) AS company, NULL::JSON AS contact, NULL::JSON AS deal,
  NULL::JSON AS contact_note, NULL::JSON AS deal_note
FROM companies c
UNION ALL
SELECT ('contact.' || co.id || '.created'), co.workspace_id,
  'contact.created', co.first_seen, co.company_id, co.sales_id,
  NULL::JSON, to_json(co.*), NULL::JSON, NULL::JSON, NULL::JSON
FROM contacts co
UNION ALL
SELECT ('contactNote.' || cn.id || '.created'), cn.workspace_id,
  'contactNote.created', cn.date, co.company_id, cn.sales_id,
  NULL::JSON, NULL::JSON, NULL::JSON, to_json(cn.*), NULL::JSON
FROM contact_notes cn JOIN contacts co ON co.workspace_id = cn.workspace_id AND co.id = cn.contact_id
UNION ALL
SELECT ('deal.' || d.id || '.created'), d.workspace_id,
  'deal.created', d.created_at, d.company_id, d.sales_id,
  NULL::JSON, NULL::JSON, to_json(d.*), NULL::JSON, NULL::JSON
FROM deals d
UNION ALL
SELECT ('dealNote.' || dn.id || '.created'), dn.workspace_id,
  'dealNote.created', dn.date, d.company_id, dn.sales_id,
  NULL::JSON, NULL::JSON, NULL::JSON, NULL::JSON, to_json(dn.*)
FROM deal_notes dn JOIN deals d ON d.workspace_id = dn.workspace_id AND d.id = dn.deal_id;

CREATE OR REPLACE FUNCTION crm_current_workspace_id() RETURNS UUID
LANGUAGE SQL STABLE AS $$
  SELECT NULLIF(current_setting('app.workspace_id', TRUE), '')::UUID
$$;

DO $$
DECLARE table_name TEXT;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'sales', 'crm_pipelines', 'crm_pipeline_stages', 'companies', 'contacts',
    'contact_notes', 'deals', 'deal_notes', 'tags', 'tasks', 'configuration',
    'crm_file_objects', 'crm_audit_events'
  ] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', table_name);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', table_name);
    EXECUTE format(
      'CREATE POLICY workspace_isolation ON %I USING (workspace_id = crm_current_workspace_id()) WITH CHECK (workspace_id = crm_current_workspace_id())',
      table_name
    );
  END LOOP;
END $$;

